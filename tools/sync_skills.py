"""Keep the Frametrace skills and the app's skill index in step.

1. The block between the `frametrace:shared-rules` markers in skills/frametrace/SKILL.md is the
   source. Every game skill (skills/frametrace-*/SKILL.md) and skills/game-skill-template.md
   carry a copy, so each skill works on its own (installed alone, or pasted into any AI).
2. frametrace/skill_index.py maps each game skill's process names (its `metadata.process_names`)
   to the skill, so the report can name the skill for the captured game.

    python tools/sync_skills.py          # copy the block, regenerate the index
    python tools/sync_skills.py --check  # list files that differ, exit 1 if any (tests run it)

Edit the rules in skills/frametrace/SKILL.md only, then run this.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

SKILLS = Path(__file__).resolve().parent.parent / "skills"
SOURCE = SKILLS / "frametrace" / "SKILL.md"
TEMPLATE = SKILLS / "game-skill-template.md"
INDEX = SKILLS.parent / "frametrace" / "skill_index.py"
RAW_URL = "https://raw.githubusercontent.com/melle62/frametrace/main/skills"

# The opening marker line (with its note) through the closing marker, inclusive.
BLOCK = re.compile(
    r"^<!-- frametrace:shared-rules\b[^\n]*-->\n.*?^<!-- /frametrace:shared-rules -->$",
    re.DOTALL | re.MULTILINE,
)


def shared_block(text: str) -> str:
    m = BLOCK.search(text)
    if not m:
        raise ValueError("no frametrace:shared-rules block")
    return m.group(0)


def frontmatter(text: str) -> dict:
    """The YAML frontmatter's top-level keys and its `metadata` map (flat, stdlib only)."""
    m = re.match(r"---\n(.*?)\n---\n", text, re.DOTALL)
    if not m:
        raise ValueError("no frontmatter")
    out: dict = {"metadata": {}}
    for line in m.group(1).splitlines():
        if line.startswith("  "):
            key, _, value = line.strip().partition(":")
            out["metadata"][key] = value.strip()
        elif ":" in line and not line.startswith("metadata:"):
            key, _, value = line.partition(":")
            out[key] = value.strip()
    return out


def listed(value: str) -> list[str]:
    """`[a.exe, b.exe]` -> ["a.exe", "b.exe"]."""
    return [v.strip() for v in value.strip("[]").split(",") if v.strip()]


def game_skills() -> list[Path]:
    return sorted(SKILLS.glob("frametrace-*/SKILL.md"))


def index_source() -> str:
    """frametrace/skill_index.py, generated from the game skills' frontmatter."""
    rows = []
    for path in game_skills():
        fm = frontmatter(path.read_text(encoding="utf-8"))
        game = fm["metadata"].get("game", "")
        for exe in listed(fm["metadata"].get("process_names", "")):
            rows.append(f'    "{exe.lower()}": ("{fm["name"]}", "{game}"),')
    return "\n".join(
        [
            '"""Which Frametrace game skill covers which process, so the report can name it.',
            "",
            "Generated by tools/sync_skills.py from skills/frametrace-*/SKILL.md (metadata.process_names).",
            'Don\'t edit by hand: change the skill, then run the tool."""',
            "",
            f'SKILLS_URL = "{RAW_URL}"',
            'GENERAL = "frametrace"',
            "",
            "# process name (lower case) -> (skill name, game)",
            "GAME_SKILLS: dict[str, tuple[str, str]] = {",
            *rows,
            "}",
            "",
        ]
    )


def targets() -> list[Path]:
    return game_skills() + [TEMPLATE]


def synced(text: str, block: str) -> str:
    if not BLOCK.search(text):
        raise ValueError("no frametrace:shared-rules markers")
    return BLOCK.sub(lambda _: block, text, count=1)


def check() -> list[Path]:
    """Skills whose shared block differs from the source, and the index if it's stale."""
    block = shared_block(SOURCE.read_text(encoding="utf-8"))
    stale = [
        p
        for p in targets()
        if not BLOCK.search(t := p.read_text(encoding="utf-8")) or shared_block(t) != block
    ]
    if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != index_source():
        stale.append(INDEX)
    return stale


def sync() -> list[Path]:
    """Copy the source block into every target; returns the files that changed."""
    block = shared_block(SOURCE.read_text(encoding="utf-8"))
    changed = []
    for p in targets():
        text = p.read_text(encoding="utf-8")
        new = synced(text, block)
        if new != text:
            p.write_text(new, encoding="utf-8", newline="\n")
            changed.append(p)
    index = index_source()
    if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != index:
        INDEX.write_text(index, encoding="utf-8", newline="\n")
        changed.append(INDEX)
    return changed


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="only report copies that differ")
    args = ap.parse_args()
    root = SKILLS.parent
    try:
        paths = check() if args.check else sync()
    except ValueError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    verb = "out of sync" if args.check else "updated"
    for p in paths:
        print(f"{verb}: {p.relative_to(root)}")
    if not paths:
        print("all skills in sync")
    return 1 if args.check and paths else 0


if __name__ == "__main__":
    sys.exit(main())
