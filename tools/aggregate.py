"""Turn the shared Frametrace dataset into the game skills' community tables.

    python tools/aggregate.py --data DIR            # DIR: a checkout of frametrace-data's data branch
    python tools/aggregate.py --data DIR --check    # exit 1 when a skill's table is out of date
    python tools/aggregate.py --data DIR --report   # every contributor's level and why (Markdown)

Everything people share stays in the dataset. This tool reads all of it, judges every
comparison from the two captures themselves (frametrace/quality.py), and lets only
one-change comparisons from trusted contributors into the table between the
`frametrace:community-data` markers of each game skill. The weekly workflow
(.github/workflows/aggregate.yml) runs it and opens a PR when a table changed.

Pairs come from two places: comparisons people opened in the Compare view, and consecutive
captures of the same game by the same contributor (most one-change runs are never opened
side by side). Per change, each contributor's runs are reduced to their median first, so one
prolific contributor can't outvote the others; the table shows the median of those.
"""

from __future__ import annotations

import argparse
import itertools
import json
import re
import statistics
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from frametrace import quality, skill_index

SKILLS = ROOT / "skills"
DATASET_URL = "https://github.com/melle62/frametrace-data"
BLOCK = re.compile(
    r"^<!-- frametrace:community-data\b[^\n]*-->\n.*?^<!-- /frametrace:community-data -->$",
    re.DOTALL | re.MULTILINE,
)
OPEN = (
    "<!-- frametrace:community-data (generated by tools/aggregate.py from the Frametrace"
    " dataset; don't edit by hand) -->"
)
CLOSE = "<!-- /frametrace:community-data -->"
# table column -> the compare delta it shows
METRICS = [
    ("Average", "Average"),
    ("1% low", "1% low"),
    ("CPU-side 1% low", "CPU-side 1% low"),
    ("GPU busy", "GPU busy, median"),
    ("PC latency", "PC latency, median"),
]


@dataclass
class Dataset:
    captures: dict[tuple[str, str], dict] = field(default_factory=dict)  # (who, id) -> data
    comparisons: list[tuple[str, str, str]] = field(default_factory=list)  # (who, a, b)
    newest: str = ""  # latest change in the dataset, for the table's date


def load(root: Path) -> Dataset:
    ds = Dataset()
    for path in sorted(root.glob("captures/*/*/*.json")):
        try:
            rec = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        data = rec.get("data")
        if isinstance(data, dict) and "analysis" in data:
            ds.captures[(rec.get("contributor", ""), rec.get("local_id", ""))] = data
            ds.newest = max(ds.newest, rec.get("updated_at") or "")
    for path in sorted(root.glob("comparisons/*/*/*.json")):
        try:
            rec = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        data = rec.get("data") or {}
        if data.get("a") and data.get("b"):
            ds.comparisons.append((rec.get("contributor", ""), data["a"], data["b"]))
            ds.newest = max(ds.newest, rec.get("updated_at") or "")
    return ds


def _exe(r: dict) -> str:
    return str(
        (r.get("game") or {}).get("exe") or (r.get("capture") or {}).get("app") or ""
    ).lower()


def candidate_pairs(ds: Dataset) -> list[tuple[str, str, str]]:
    """(who, a, b): compared pairs, plus consecutive captures of one game by one contributor."""
    pairs = {
        p for p in ds.comparisons if (p[0], p[1]) in ds.captures and (p[0], p[2]) in ds.captures
    }
    runs: dict[tuple[str, str], list[tuple[str, str]]] = defaultdict(list)
    for (who, cid), r in ds.captures.items():
        runs[(who, _exe(r))].append(((r.get("capture") or {}).get("started") or "", cid))
    for (who, _), items in runs.items():
        items.sort()
        pairs.update((who, a, b) for (_, a), (_, b) in itertools.pairwise(items))
    return sorted(pairs)


@dataclass
class Judged:
    who: str
    a: str
    b: str
    pair: quality.Pair
    exe: str
    gpu: str
    resolution: str


def judge(ds: Dataset) -> tuple[list[Judged], dict[str, quality.Contributor]]:
    judged = []
    for who, a, b in candidate_pairs(ds):
        ra, rb = ds.captures[(who, a)], ds.captures[(who, b)]
        disp = quality.main_display(rb)
        judged.append(
            Judged(
                who,
                a,
                b,
                quality.judge_pair(ra, rb),
                _exe(rb),
                quality.main_gpu(rb).get("name") or "?",
                f"{disp.get('width')}×{disp.get('height')}" if disp.get("width") else "?",
            )
        )
    by_who: dict[str, list[dict]] = defaultdict(list)
    for (who, _), r in ds.captures.items():
        by_who[who].append(r)
    people = {
        who: quality.judge_contributor(who, caps, [j.pair for j in judged if j.who == who])
        for who, caps in by_who.items()
    }
    return judged, people


def _short_gpu(name: str) -> str:
    return re.sub(r"^(NVIDIA GeForce|AMD Radeon|Intel\(R\))\s+", "", name).strip()


def _pct(v: float | None) -> str:
    if v is None:
        return "n/a"
    return f"{v:+.1f}%".replace("-", "−")


def rows_for(exe_names: set[str], judged: list[Judged], people: dict) -> list[dict]:
    """One row per (setting, A value, B value), from trusted contributors' usable pairs."""
    groups: dict[tuple[str, str, str], list[Judged]] = defaultdict(list)
    for j in judged:
        if j.exe in exe_names and j.pair.usable_for_costs and people[j.who].level == "trusted":
            groups[tuple(j.pair.changes[0])].append(j)
    out = []
    for (key, va, vb), items in groups.items():
        row = {
            "key": key,
            "a": va,
            "b": vb,
            "runs": len(items),
            "people": len({j.who for j in items}),
            "who": sorted({j.who for j in items}),
            "gpus": sorted({_short_gpu(j.gpu) for j in items}),
            "resolutions": sorted({j.resolution for j in items}),
        }
        for column, delta in METRICS:
            per_person = []
            for who in sorted({j.who for j in items}):
                values = [
                    j.pair.deltas[delta].change
                    for j in items
                    if j.who == who
                    and delta in j.pair.deltas
                    and j.pair.deltas[delta].change is not None
                ]
                if values:
                    per_person.append(statistics.median(values))
            row[column] = statistics.median(per_person) if per_person else None
        out.append(row)
    out.sort(key=lambda r: (-r["people"], -r["runs"], r["key"], r["a"], r["b"]))
    return out


def table(rows: list[dict], newest: str) -> str:
    if not rows:
        body = (
            "No community data yet. One-change comparisons by trusted contributors in the"
            f" [Frametrace dataset]({DATASET_URL}) appear here (median change from A to B, with"
            " the GPUs they were measured on)."
        )
        return f"{OPEN}\n{body}\n{CLOSE}"
    runs = sum(r["runs"] for r in rows)
    people = len({w for r in rows for w in r["who"]})
    lines = [
        OPEN,
        (
            f"**Community data** from the [Frametrace dataset]({DATASET_URL}): one-change"
            " comparisons by trusted contributors (same system, same scene, both runs clean),"
            " median change from A to B; each person's runs count once. As of"
            f" {newest[:10] or 'unknown'}: {runs} comparison{'s' if runs != 1 else ''} from"
            f" {people} {'people' if people != 1 else 'person'}."
        ),
        "",
        "| Setting | A → B | Runs | People | "
        + " | ".join(c for c, _ in METRICS)
        + " | Measured on |",
        "|---|---|---|---|" + "---|" * len(METRICS) + "---|",
    ]
    for r in rows:
        where = ", ".join(r["gpus"][:3]) + (" …" if len(r["gpus"]) > 3 else "")
        where += f" ({', '.join(r['resolutions'][:2])})"
        lines.append(
            f"| `{r['key']}` | {r['a']} → {r['b']} | {r['runs']} | {r['people']} | "
            + " | ".join(_pct(r[c]) for c, _ in METRICS)
            + f" | {where} |"
        )
    lines.append(CLOSE)
    return "\n".join(lines)


def game_skills() -> dict[Path, set[str]]:
    """Each game skill's SKILL.md and the process names it covers."""
    out: dict[Path, set[str]] = defaultdict(set)
    for exe, (skill, _game) in skill_index.GAME_SKILLS.items():
        out[SKILLS / skill / "SKILL.md"].add(exe)
    return dict(out)


def render(path: Path, text: str, block: str) -> str:
    if not BLOCK.search(text):
        raise ValueError(f"{path}: no frametrace:community-data markers")
    return BLOCK.sub(lambda _: block, text, count=1)


def report(judged: list[Judged], people: dict) -> str:
    lines = [
        "## Contributors",
        "",
        (
            "| Contributor | Level | Captures | Mean capture score | One-change comparisons"
            " | Baseline pairs (agreeing) |"
        ),
        "|---|---|---|---|---|---|",
    ]
    for p in sorted(people.values(), key=lambda p: (p.level != "trusted", -p.captures, p.key)):
        lines.append(
            f"| `{p.key}` | {p.level} | {p.captures} | {p.mean_capture_score:.0f} |"
            f" {p.one_change} | {p.baselines} ({p.agreeing_baselines}) |"
        )
    usable = sum(j.pair.usable_for_costs for j in judged)
    lines += ["", f"{len(judged)} pairs judged, {usable} usable for setting costs."]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--data", required=True, type=Path, help="checkout of the dataset's data branch"
    )
    ap.add_argument("--check", action="store_true", help="exit 1 if a skill's table is stale")
    ap.add_argument("--report", action="store_true", help="print contributor levels (Markdown)")
    args = ap.parse_args(argv)

    ds = load(args.data)
    judged, people = judge(ds)
    stale = []
    for path, exes in game_skills().items():
        text = path.read_text(encoding="utf-8")
        new = render(path, text, table(rows_for(exes, judged, people), ds.newest))
        if new != text:
            stale.append(path)
            if not args.check:
                path.write_text(new, encoding="utf-8")
    if args.report:
        print(report(judged, people))
    for path in stale:
        verb = "out of date" if args.check else "updated"
        print(f"{verb}: {path.relative_to(ROOT)}", file=sys.stderr)
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
